<?php

declare(strict_types=1);

namespace App\Contracts;

/**
 * Объект заявки, который сам определяет варианты для полей формы.
 *
 * Набор полей подраздела задаёт ServiceType, но у части полей варианты зависят
 * от конкретного объекта: у зарубежной регаты это предлагаемые варианты
 * участия и список свободных чартерных яхт — у каждой регаты свой.
 *
 * Отдельный интерфейс, а не метод в ServiceSubject: объектам без переменных
 * полей (походы) реализовывать нечего.
 */
interface ServiceOptionProvider
{
    /**
     * Варианты для полей формы: ключ поля из ServiceType::payloadFields() =>
     * [значение => подпись]. Поля, которых здесь нет, остаются как объявлены.
     *
     * @return array<string, array<string, string>>
     */
    public function serviceOptions(): array;

    /**
     * Подпись уже сохранённого значения — для письма и админки.
     *
     * Нужна отдельно от serviceOptions(): там только то, что можно выбрать
     * сейчас, а выбранная вчера яхта к моменту просмотра заявки уже занята и
     * из списка вариантов ушла.
     */
    public function serviceOptionLabel(string $field, string $value): ?string;
}
