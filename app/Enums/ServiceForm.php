<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Форма, из которой пришла заявка на услугу.
 *
 * У подраздела может быть больше одной формы: у мероприятий рядом с общей
 * модалкой «Обсудить мероприятие» живёт «Конструктор мероприятия» (ТЗ 3-го
 * этапа, п. 7) — двенадцать параметров, подбор яхт и расчёт стоимости.
 * Поля обеих форм описаны в одном месте (@see ServiceType::payloadFields()),
 * а этот enum говорит, какие из них показывает и принимает конкретная форма:
 * иначе модалка спрашивала бы параметры конструктора, а конструктор не смог
 * бы сохранить свои — белый список payload строится по тому же описанию.
 */
enum ServiceForm: string
{
    /** Общая модалка «Оставить заявку» — она же форма по умолчанию. */
    case Modal = 'modal';

    /** Конструктор мероприятия на /services/events. */
    case EventConstructor = 'constructor';
}
