<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Кому адресовано уведомление о новом сообщении в чате.
 *
 * Раньше это был булев флаг `forSupport`, которого хватало на два состояния.
 * С появлением личных переписок по объявлениям состояний стало три: у каждого
 * свой заголовок и своя страница назначения — операторская в админ-панели либо
 * одна из двух в личном кабинете.
 */
enum ChatNotificationAudience: string
{
    /** Операторам: клиент написал в поддержку. */
    case Support = 'support';

    /** Клиенту: поддержка ответила. */
    case Client = 'client';

    /** Собеседнику в личной переписке (объявление биржи, барахолки). */
    case Direct = 'direct';
}
